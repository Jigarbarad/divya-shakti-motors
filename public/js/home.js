let featured = [];
function renderBikes() {
  App.$('#bikeGrid').innerHTML = featured.length ? featured.map(App.card).join('') : '';
  App.renderHours(App.$('#hours'), App.$('#status'));
}

App.init('home', async () => {
  try {
    const all = await App.loadProducts();
    const f = all.filter((p) => p.featured);
    featured = (f.length ? f : all).slice(0, 4);
  } catch (e) { /* grid just stays empty */ }
  App.bindCards(App.$('#bikeGrid'));
  renderBikes();
  App.onLang(renderBikes);
});
